#!/usr/bin/env python3
"""Turn a PSF2 console font into font.js: 256 glyphs of 8x16 in CP437 order.

Usage: mkfont.py FONT.psfu[.gz] > font.js

Glyphs are looked up through the font's Unicode table, so the output is in
CP437 order whatever order the font file uses. Fails if a glyph is missing.
"""
import base64
import gzip
import struct
import sys

# CP437 as shown on screen: codes 0-31 and 127 are pictures, not controls.
LOW = "\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


def cp437_char(code):
    if code < 32:
        return LOW[code]
    if code == 127:
        return "⌂"
    return bytes([code]).decode("cp437")


def main():
    if len(sys.argv) != 2 or sys.argv[1] in ("-h", "--help"):
        sys.exit(__doc__)
    path = sys.argv[1]
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as fh:
        data = fh.read()
    magic, _ver, hdr, flags, count, size, height, width = struct.unpack_from("<8I", data)
    if magic != 0x864AB572 or (height, width) != (16, 8) or not flags & 1:
        sys.exit("need a PSF2 8x16 font with a Unicode table")
    glyphs = [data[hdr + i * size: hdr + (i + 1) * size] for i in range(count)]
    table = data[hdr + count * size:]
    by_char = {}
    for index, entry in enumerate(table.split(b"\xff")[:count]):
        # an entry is single characters, then 0xFE-separated sequences
        for ch in entry.split(b"\xfe")[0].decode("utf-8"):
            by_char.setdefault(ch, index)
    out = bytearray()
    missing = []
    for code in range(256):
        ch = cp437_char(code)
        if code in (0, 255):                    # blank cells
            out += bytes(16)
        elif ch in by_char:
            out += glyphs[by_char[ch]]
        else:
            missing.append(code)
            out += glyphs[code]
    if missing:
        sys.exit("font lacks CP437 codes: %s" % missing)
    print("/* generated by tools/mkfont.py - 256 CP437 glyphs, 8x16, one byte per row */")
    print('const TINY_FONT = "%s";' % base64.b64encode(bytes(out)).decode())


if __name__ == "__main__":
    main()
